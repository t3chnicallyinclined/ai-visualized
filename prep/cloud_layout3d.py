"""Lay out a model's whole vocabulary in 3D for the show's 3D cloud (run once per model, offline).

Same recipe as cloud_layout.py (L2-normalised embedding rows, PCA to 128, openTSNE, cosine, perplexity 30,
seed 42) but with three output dimensions. openTSNE's FFT gradient only does 1D and 2D, so this uses the
Barnes-Hut gradient, which is slower; a 50,000-token vocabulary takes tens of minutes on a desktop CPU.
Then it measures how many true neighbours the 3D map keeps (recall@10), like the 2D script, so the page
can say so.

Usage:  python prep/cloud_layout3d.py <model folder> <output .js> <model key> "<model name>" [threads]
        e.g. python prep/cloud_layout3d.py tinyllama-15M/ cloud3d-tiny.js tiny-stories "TinyStories 15M" 6
Writes: the output file, which registers itself as window.CLOUDS3D[<model key>] = { meta, xyz } with xyz as
        base64 of V x 3 uint16 (65535 = left out; the categories live in the 2D file).
"""
import base64, json, sys, time, unicodedata
from pathlib import Path

import numpy as np
import torch
from safetensors.torch import load_file
from openTSNE import TSNE

src, out, key, name = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3], sys.argv[4]
threads = int(sys.argv[5]) if len(sys.argv) > 5 else 4
W = load_file(str(src / "model.safetensors"))
EMB = ["model.embed_tokens.weight", "gpt_neox.embed_in.weight", "transformer.wte.weight", "backbone.embeddings.weight"]
E = W[next(k for k in EMB if k in W)].float()
V = E.shape[0]
tok = json.loads((src / "tokenizer.json").read_text(encoding="utf-8"))
vocab = {i: s for s, i in tok["model"]["vocab"].items()}
for a in tok["added_tokens"]:
    vocab[a["id"]] = a["content"]

# the same text() and categories as cloud_layout.py, so exactly the same tokens are laid out
# GPT-2 byte-level alphabet, to turn a vocab entry back into its text
bs = list(range(33, 127)) + list(range(161, 173)) + list(range(174, 256))
cs, n = bs[:], 0
for b in range(256):
    if b not in bs:
        bs.append(b); cs.append(256 + n); n += 1
dec = {chr(c): b for b, c in zip(bs, cs)}

sentencepiece = bool(tok["model"].get("byte_fallback"))  # Llama-style: "▁" for spaces, <0xNN> byte tokens
special = {a["id"] for a in tok["added_tokens"] if a.get("special")}

def text(i):
    raw = vocab.get(i, "")
    if i in special:
        return None, raw
    if sentencepiece:
        if raw.startswith("<0x") and raw.endswith(">"):
            return None, raw  # a single byte: left out, like byte fragments
        return raw.replace("▁", " "), raw
    try:
        return bytes(dec[ch] for ch in raw).decode("utf-8"), raw
    except (KeyError, UnicodeDecodeError):
        return None, raw

cat = np.full(V, 255, dtype=np.uint8)
for i in range(V):
    t, raw = text(i)
    if t is None or raw.startswith("<|") or not t:
        continue
    s = t.strip()
    if not s:
        cat[i] = 3
    elif all(ch.isdigit() for ch in s):
        cat[i] = 2
    elif all(unicodedata.category(ch)[0] in "PZS" for ch in s):
        cat[i] = 3
    elif any(ord(ch) > 0x24F and ch.isalpha() for ch in s):
        cat[i] = 5
    elif s.isalpha():
        cat[i] = 0 if t.startswith(" ") else 1
    else:
        cat[i] = 4
keep = np.where(cat != 255)[0]
print(f"vocabulary {V}, laid out {len(keep)}, left out {V - len(keep)}; {threads} threads", flush=True)

torch.manual_seed(0)
X = torch.nn.functional.normalize(E[keep], dim=1)
U, S, Vt = torch.pca_lowrank(X - X.mean(0), q=128, center=False)
Z = ((X - X.mean(0)) @ Vt[:, :128]).numpy().astype(np.float64)
t0 = time.time()
emb = TSNE(n_components=3, perplexity=30, metric="cosine", initialization="pca", negative_gradient_method="bh",
           random_state=42, n_jobs=threads, verbose=True).fit(Z)
Y = np.asarray(emb)
print(f"t-SNE 3D took {time.time() - t0:.0f} s", flush=True)

rng = np.random.default_rng(0)
sample = rng.choice(len(keep), 3000, replace=False)
sims = X[sample] @ X.T
sims[torch.arange(3000), torch.as_tensor(sample)] = -2
true_nn = torch.topk(sims, 10, dim=1).indices.numpy()
Yt = torch.as_tensor(Y)
d2 = torch.cdist(Yt[sample], Yt)
d2[torch.arange(3000), torch.as_tensor(sample)] = 1e18
def recall_at(k):
    map_nn = torch.topk(d2, k, dim=1, largest=False).indices.numpy()
    return float(np.mean([len(set(a) & set(b)) / 10 for a, b in zip(true_nn, map_nn)]))
recall, recall100 = recall_at(10), recall_at(100)
print(f"3D recall@10 = {recall:.3f}; true 10 found within the 100 nearest = {recall100:.3f}", flush=True)

lo, hi = Y.min(0), Y.max(0)
xyz = np.full((V, 3), 65535, dtype=np.uint16)
xyz[keep] = np.round((Y - lo) / (hi - lo) * 65534).astype(np.uint16)
meta = {"model": name, "tokens": int(len(keep)), "perplexity": 30, "seed": 42, "recall10": round(recall, 3), "recall100": round(recall100, 3),
        "method": "openTSNE 1.0.4 (Barnes-Hut, 3 components) on L2-normalised embedding rows, PCA to 128, cosine"}
out.write_text(
    f"// 3D token-cloud map of {name}'s vocabulary. Generated by prep/cloud_layout3d.py; do not edit by hand.\n"
    "window.CLOUDS3D = window.CLOUDS3D || {};\n"
    f"window.CLOUDS3D[{json.dumps(key)}] = {{ meta: {json.dumps(meta)},\n"
    f"  xyz: '{base64.b64encode(xyz.tobytes()).decode()}' }};\n",
    encoding="utf-8")
print(f"wrote {out} ({out.stat().st_size // 1024} KB)")
